public class VariaveisComplexas {
    public static void main(String[] args) {
        //CRIANDO OS PRIMEIROS VETORES EM JAVA
        
        int [] idade = {15,16,12,19,20};
        String [] nome = {"Ana", "Pedro", "Luiza", "Maria", "Kaio"};
        double [] salarios = {1800,1512.50,2500.83, 1912.90,600};
        
        //IMPRIMIR OS DADOS DA PRIEIRA PESSSOA
        
        System.out.println("======================");
        System.out.println("Nome:"+nome[0]);
        System.out.println("Idade:"+idade[0]);
        System.out.println("Salario:R$"+salarios[0]);
        
        //IMPRIMIR OS DADOS DA SEGUNDA PESSSOA
        
        System.out.println("======================");
        System.out.println("Nome:"+nome[1]);
        System.out.println("Idade:"+idade[1]);
        System.out.println("Salario:R$"+salarios[1]);
        
        //IMPRIMIR OS DADOS DA TERCEIRA PESSSOA
        
        System.out.println("======================");
        System.out.println("Nome:"+nome[2]);
        System.out.println("Idade:"+idade[2]);
        System.out.println("Salario:R$"+salarios[2]);
        
        //IMPRIMIR OS DADOS DA QUARTA PESSSOA
        
        System.out.println("======================");
        System.out.println("Nome:"+nome[3]);
        System.out.println("Idade:"+idade[3]);
        System.out.println("Salario:R$"+salarios[3]);
        
        //IMPRIMIR OS DADOS DA QUINTA PESSSOA
        
        System.out.println("======================");
        System.out.println("Nome:"+nome[4]);
        System.out.println("Idade:"+idade[4]);
        System.out.println("Salario:R$"+salarios[4]);
        System.out.println("======================");
    }
}
